const DICT = { en, cs, ru };

// Used until a language is picked with the globe button or in Settings.
export const DEFAULT_LANG = "ru";

let lang = DEFAULT_LANG;

export function setLang(code) {
  lang = DICT[code] ? code : "en";
  document.documentElement.lang = lang;
}

export const getLang = () => lang;
export const locale = () => LOCALES[lang];

// Looks a key up in a given language (falling back to English) and fills its placeholders.
export function tIn(code, key, vars = {}) {
  let value = DICT[code]?.[key] ?? en[key] ?? key;
  if (typeof value === "object") value = value[new Intl.PluralRules(code).select(vars.n ?? 0)] ?? value.other;
  return value.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ""));
}

export const t = (key, vars) => tIn(lang, key, vars);
